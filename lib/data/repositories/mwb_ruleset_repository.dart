/// Personalisation rules for MWB editions. Local assets today; a future
/// implementation can fetch reviewed rules from the MWB (Laravel) API behind
/// the same interface.
abstract interface class MwbRulesetRepository {
  /// MWB edition ids that have a ruleset.
  Set<String> get editions;

  /// The ruleset for an MWB edition. Throws [FeatureUnavailableFailure] if
  /// the edition has none.
  Future<MwbRuleset> ruleset(String targetVersionId);
}

/// Parses a ruleset document. Malformed rules are skipped and reported in
/// [MwbRuleset.loadIssues] so one bad rule never blocks the others.
MwbRuleset parseMwbRuleset(String raw) {
  final j = jsonDecode(raw) as Map<String, dynamic>;
  final source = j['sourceVersionId'] as String;
  final target = j['targetVersionId'] as String;
  final rules = <MwbRule>[];
  final issues = <String>[];
  final list = (j['rules'] as List?) ?? const [];
  for (var i = 0; i < list.length; i++) {
    final item = list[i];
    try {
      rules.add(MwbRule.fromJson(item as Map<String, dynamic>, sourceVersionId: source, targetVersionId: target));
    } catch (e) {
      final id = item is Map ? item['id'] : null;
      issues.add('Rule ${id ?? '#$i'} could not be read: $e');
    }
  }
  final sup = j['theologicalSupervisor'] as Map<String, dynamic>?;
  return MwbRuleset(
    sourceVersionId: source,
    targetVersionId: target,
    rulesetVersion: j['rulesetVersion'] as int? ?? 1,
    style: VersionStyleProfile.fromJson(source, j['style'] as Map<String, dynamic>?),
    rules: rules,
    supervisor: sup == null ? null : TheologicalSupervisor(name: sup['name'] as String, role: sup['role'] as String),
    loadIssues: issues,
  );
}

/// The complete per-verse personalisation catalogue of each MWB edition
/// (generated by `tool/build_personalisation_catalogue.js`).
abstract interface class PersonalisationCatalogueRepository {
  Future<PersonalisationCatalogue> catalogue(String targetVersionId);
}

class AssetPersonalisationCatalogueRepository implements PersonalisationCatalogueRepository {
  AssetPersonalisationCatalogueRepository({AssetLoader? loader}) : _loader = loader ?? rootBundle.loadString;

  final AssetLoader _loader;
  final Map<String, Future<PersonalisationCatalogue>> _cache = {};

  static const assets = {
    'KJV-MWB': 'assets/mwb/catalogue/kjv-mwb.catalogue.json',
    'WEB-MWB': 'assets/mwb/catalogue/web-mwb.catalogue.json',
  };

  @override
  Future<PersonalisationCatalogue> catalogue(String targetVersionId) {
    final asset = assets[targetVersionId];
    if (asset == null) {
      return Future.error(FeatureUnavailableFailure('No personalisation catalogue exists for $targetVersionId.'));
    }
    return _cache.putIfAbsent(targetVersionId, () async {
      try {
        final raw = await _loader(asset);
        return _parseCatalogue(raw);
      } catch (_) {
        _cache.remove(targetVersionId);
        throw const UnknownFailure('The personalisation catalogue could not be opened.');
      }
    });
  }
}

PersonalisationCatalogue _parseCatalogue(String raw) =>
    PersonalisationCatalogue.fromJson(jsonDecode(raw) as Map<String, dynamic>);

class AssetMwbRulesetRepository implements MwbRulesetRepository {
  /// [catalogue] adds the generated proposals of each edition's catalogue to
  /// its hand-authored ruleset. Hand-authored rules win: a generated proposal
  /// is skipped for any verse that already has a hand-authored rule.
  AssetMwbRulesetRepository({AssetLoader? loader, PersonalisationCatalogueRepository? catalogue})
    : _loader = loader ?? rootBundle.loadString,
      _catalogue = catalogue; // ignore: prefer_initializing_formals

  final AssetLoader _loader;
  final PersonalisationCatalogueRepository? _catalogue;
  final Map<String, Future<MwbRuleset>> _cache = {};

  static const _assets = {'KJV-MWB': 'assets/mwb/rulesets/kjv-mwb.json', 'WEB-MWB': 'assets/mwb/rulesets/web-mwb.json'};

  @override
  Set<String> get editions => _assets.keys.toSet();

  @override
  Future<MwbRuleset> ruleset(String targetVersionId) {
    final asset = _assets[targetVersionId];
    if (asset == null) {
      return Future.error(FeatureUnavailableFailure('No personalisation rules exist for $targetVersionId.'));
    }
    return _cache.putIfAbsent(targetVersionId, () async {
      final MwbRuleset base;
      try {
        base = parseMwbRuleset(await _loader(asset));
      } catch (_) {
        _cache.remove(targetVersionId);
        throw const UnknownFailure('The personalisation rules could not be opened.');
      }
      final catalogue = _catalogue;
      if (catalogue == null) return base;
      var rules = base.rules;
      try {
        final generated = (await catalogue.catalogue(targetVersionId)).proposals;
        final handVerses = {for (final r in base.rules) r.reference.key};
        rules = [...base.rules, ...generated.where((g) => !handVerses.contains(g.reference.key))];
      } catch (_) {
        // The hand-authored rules still work without the catalogue.
      }
      // Decisions returned by reviewers and imported with
      // tool/import_review_decisions.js, applied to their exact proposal id.
      try {
        final raw = await _loader('assets/mwb/reviews/${targetVersionId.toLowerCase()}.decisions.json');
        final decisions = (jsonDecode(raw) as Map<String, dynamic>)['decisions'] as Map<String, dynamic>? ?? const {};
        if (decisions.isNotEmpty) {
          rules = [
            for (final r in rules)
              r.withReviews([
                for (final d in (decisions[r.id] as List? ?? const []).cast<Map<String, dynamic>>()) ReviewRecord.fromJson(d),
              ]),
          ];
        }
      } catch (_) {
        // No imported decisions.
      }
      return MwbRuleset(
        sourceVersionId: base.sourceVersionId,
        targetVersionId: base.targetVersionId,
        rulesetVersion: base.rulesetVersion,
        style: base.style,
        supervisor: base.supervisor,
        loadIssues: base.loadIssues,
        rules: rules,
      );
    });
  }
}
